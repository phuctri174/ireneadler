r"""Train the zoom classifier on the captured sessions and export it for the HUD -
only if it beats the live one on a session it never saw.

    .venv\Scripts\python scripts\zoom_train.py [--holdout zoom_panel-<session>] [--force]

One session is held out (default: the latest zoom_panel run - the distance he
actually uses the panel from; with no panel run, nothing is held out and the old
behaviour stands). The candidate is trained on everything else, then it and the
live forest (git HEAD) are replayed through the HUD's real gate on the held-out
session (scripts/zoom_eval.py, the "strict" timing). It ships only if it has
fewer false zooms on the confusers - or as few, with fewer latched confuser
frames - and its zoom recall is no worse. --force writes it regardless.

Writes hud/src/tracking/zoomModel.json: a gradient-boosted forest small enough to
evaluate per frame in the browser (60 trees, depth 3), plus the feature order it
expects. hud/src/tracking/zoomFeatures.ts builds that vector live and must stay in
step - core/tests/test_zoom_model.py checks the two agree frame for frame.

The trees are compared against scikit-learn's own predictions before anything is
written, so an export that would not reproduce the model fails here rather than
silently misbehaving on the matrix.
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent))

from irene.calibration import load_family  # noqa: E402
from zoom_analyze import FEATURE_NAMES, clips, dataset  # noqa: E402

OUT = HERE.parents[1] / "hud" / "src" / "tracking" / "zoomModel.ts"
GOLDEN = HERE.parents[1] / "hud" / "tests" / "zoom.golden.json"
TREES = 60
DEPTH = 3

# The model ships as a module rather than a .json file: no bundler setting, no
# runtime JSON-import attribute, just a value the HUD imports like any other.
MODULE_HEADER = '''// Generated by core/scripts/zoom_train.py from the captures in core/calibration.
// Do not edit by hand - retrain after a new capture.
//
// A gradient-boosted forest over the 24 features in zoomFeatures.ts: the raw score
// is the baseline plus one leaf from each tree, and a zoom pose is raw >= 0.

export interface ZoomTree {
  feature: number[];
  threshold: number[];
  left: number[];
  right: number[];
  leaf: boolean[];
  value: number[];
}

export interface ZoomForest {
  baseline: number;
  features: string[];
  trees: ZoomTree[];
}

'''


def export(model) -> dict:
    """The forest as plain arrays: every node is (feature, threshold, left, right)
    or a leaf value."""
    trees = []
    for group in model._predictors:
        for predictor in group:
            nodes = predictor.nodes
            trees.append(
                {
                    "feature": [int(n["feature_idx"]) for n in nodes],
                    "threshold": [float(n["num_threshold"]) for n in nodes],
                    "left": [int(n["left"]) for n in nodes],
                    "right": [int(n["right"]) for n in nodes],
                    "leaf": [bool(n["is_leaf"]) for n in nodes],
                    "value": [float(n["value"]) for n in nodes],
                }
            )
    return {
        "_about": "Zoom pose classifier - see core/scripts/zoom_train.py. raw = baseline + sum of one leaf per tree; zoom pose if 1/(1+exp(-raw)) >= 0.5.",
        "baseline": float(model._baseline_prediction.ravel()[0]),
        "features": list(FEATURE_NAMES),
        "trees": trees,
    }


def rounded(row) -> list[float]:
    """The feature row as the golden file will hold it: plain floats, six places.
    Rounding through float() rather than numpy keeps it at double precision, so
    what is written and what is scored are the same numbers."""
    return [round(float(v), 6) for v in row]


def predict_raw(spec: dict, x) -> float:
    """The exported forest, evaluated the way the HUD will evaluate it."""
    total = spec["baseline"]
    for tree in spec["trees"]:
        node = 0
        while not tree["leaf"][node]:
            f = tree["feature"][node]
            node = tree["left"][node] if x[f] <= tree["threshold"][node] else tree["right"][node]
        total += tree["value"][node]
    return total


HOLDOUT_SHARE = 0.45


def split_session(all_takes: dict, held: str) -> tuple[dict, dict]:
    """(train, test) with one session split inside: a pose with several reps
    gives its later ~45% of reps to the test; a single take gives the last 45% of
    its frames, after a gap of WINDOW frames so no test frame's features reach
    back into the training half."""
    from zoom_analyze import WINDOW

    train = {k: v for k, v in all_takes.items() if f"{k[0]}-{k[1]}" != held}
    test: dict = {}
    mine = {k: v for k, v in all_takes.items() if f"{k[0]}-{k[1]}" == held}
    poses = sorted({k[2] for k in mine})
    for pose in poses:
        reps = sorted(k for k in mine if k[2] == pose)
        if len(reps) > 1:
            n_test = max(1, round(len(reps) * HOLDOUT_SHARE))
            for k in reps[:-n_test]:
                train[k] = mine[k]
            for k in reps[-n_test:]:
                test[k] = mine[k]
        else:
            k = reps[0]
            frames = mine[k]
            cut = int(len(frames) * (1 - HOLDOUT_SHARE))
            train[k] = frames[:cut]
            test[(k[0], k[1], k[2], f"{k[3]}b")] = frames[cut + WINDOW:]
    return train, test


def beats(new: dict, live: dict) -> tuple[bool, str]:
    """Does the candidate beat the live forest on the held-out session?"""
    nf, lf = new["false"][0], live["false"][0]
    fewer = nf < lf or (nf == lf and new["conf_frames"] < live["conf_frames"])
    recall_ok = new["recall"][0] >= live["recall"][0] and new["zoom_frames"] >= live["zoom_frames"] - 0.05
    if not fewer:
        return False, f"not fewer false zooms ({nf} vs {lf} takes, {new['conf_frames']:.1%} vs {live['conf_frames']:.1%} of frames)"
    if not recall_ok:
        return False, "fewer false zooms, but it zooms less when he means it"
    return True, f"fewer false zooms ({nf} vs {lf} takes, {new['conf_frames']:.1%} vs {live['conf_frames']:.1%} of frames), recall no worse"


def main() -> int:
    import argparse

    parser = argparse.ArgumentParser()
    parser.add_argument("--holdout", default=None, help="profile-session to keep out of training and test on")
    parser.add_argument("--force", action="store_true", help="write the model even if it does not beat the live one")
    args = parser.parse_args()

    frames = load_family("zoom")
    if not frames:
        print("no zoom captures in core/calibration - run ctrl+alt+shift+1/2/3/8 first")
        return 1
    all_takes = clips(frames)
    runs = sorted({(f["profile"], f["session"]) for f in frames})
    panel_runs = [f"{p}-{s}" for p, s in runs if p == "zoom_panel"]
    held = args.holdout or (panel_runs[-1] if panel_runs else None)
    split = held in panel_runs and len(panel_runs) < 2 and not args.holdout
    if split:
        # one panel session: holding all of it out would leave the model with no
        # panel-distance frames at all, so it is split by take instead - later reps
        # held out, single takes cut in time with a gap the feature window can't
        # bridge. Weaker than a separate session (same day, same light); a second
        # ctrl+alt+shift+8 run makes it a real held-out session.
        print(f"only one zoom_panel session: splitting {held} by take (later reps / the end of each single take held out)")
        takes, test = split_session(all_takes, held)
    else:
        takes = {k: v for k, v in all_takes.items() if f"{k[0]}-{k[1]}" != held}
        test = {k: v for k, v in all_takes.items() if f"{k[0]}-{k[1]}" == held}
        runs = [r for r in runs if f"{r[0]}-{r[1]}" != held]
    if held and not test:
        print(f"holdout {held!r} matched nothing")
        return 1
    X, y = dataset(takes)
    print(f"training on {len(X)} frames from {len(runs)} sessions, {X.shape[1]} features")
    for profile, session in runs:
        print(f"  {profile:10} {session}")
    missing = [p for p in ("zoom_near", "zoom_mid", "zoom_far") if not any(r[0] == p for r in runs)]
    if missing:
        print(f"  WARNING: no capture at {', '.join(missing)} - the model has never seen that distance")

    from sklearn.ensemble import HistGradientBoostingClassifier

    model = HistGradientBoostingClassifier(max_iter=TREES, max_depth=DEPTH, random_state=0).fit(X, y)
    spec = export(model)

    # the export has to reproduce sklearn exactly, or the HUD is running a
    # different classifier from the one that was measured
    want = model.decision_function(X)
    got = np.array([predict_raw(spec, row) for row in X])
    drift = float(np.max(np.abs(want - got)))
    agree = float(np.mean((want >= 0) == (got >= 0)))
    print(f"\nexport check: max raw-score drift {drift:.2e}, decisions agree {agree:.4%}")
    if drift > 1e-6 or agree < 1.0:
        print("EXPORT DOES NOT MATCH THE MODEL - not writing")
        return 1

    if test:
        from zoom_eval import GATES, evaluate, line, load_forest

        print(f"\nheld out: {held} ({len(test)} takes) - through the HUD's gate (strict timing)")
        live = evaluate(test, load_forest("HEAD"), GATES["strict"])
        new = evaluate(test, spec, GATES["strict"])
        print("  " + line("live (HEAD)", live))
        print("  " + line("retrained", new))
        ok, why = beats(new, live)
        print(f"  verdict: {'SHIP' if ok else 'DO NOT SHIP'} - {why}")
        if not ok and not args.force:
            print("not writing: the live model stays")
            return 2

    nodes = sum(len(t["value"]) for t in spec["trees"])
    # written as a module rather than a .json file so it needs no bundler or
    # runtime support for JSON imports - it is just a value the HUD imports
    body = json.dumps({k: v for k, v in spec.items() if k != "_about"}, separators=(",", ":"))
    OUT.write_text(MODULE_HEADER + f"export const ZOOM_FOREST: ZoomForest = {body};\n", encoding="utf-8")
    size = OUT.stat().st_size
    print(f"wrote {OUT.relative_to(HERE.parents[1])}: {len(spec['trees'])} trees, {nodes} nodes, {size / 1024:.0f} KB")
    hit = float(np.mean((want >= 0) == (y == 1)))
    print(f"fit on its own training data: {hit:.2%} (held-out numbers come from zoom_analyze.py)")
    write_golden(takes, spec)
    return 0


def write_golden(takes: dict, spec: dict) -> None:
    """A few whole takes, with the features and score Python computed for every
    frame, so the TypeScript port can be held to them (hud/tests/zoom.verify.mjs)."""
    from zoom_analyze import take_features

    picked = []
    for pose in ("zoom_in", "zoom_out_fast", "waving", "fist"):
        key = next((k for k in sorted(takes) if k[2] == pose), None)
        if key is None:
            continue
        frames = takes[key]
        feats = take_features(frames)
        picked.append(
            {
                "take": f"{key[0]}/{key[2]}/rep{key[3]}",
                "frames": [
                    {
                        "in": {k: f.get(k) for k in ("thumb", "index", "middle", "ring", "pinky", "spread", "ratio",
                                                     "tipGapPalm", "knuckleGapPalm", "palmSpan", "cx", "cy", "ts", "lm")},
                        # the score is of the exact numbers written here, not of the
                        # full-precision row: that way the other side can be held to
                        # the same input, and the float differences between the two
                        # languages stay a question about the features rather than
                        # about the forest
                        "features": rounded(row),
                        "raw": round(predict_raw(spec, rounded(row)), 6),
                    }
                    for f, row in zip(frames, feats)
                ],
            }
        )
    GOLDEN.write_text(json.dumps(picked, separators=(",", ":")), encoding="utf-8")
    n = sum(len(t["frames"]) for t in picked)
    print(f"wrote {GOLDEN.relative_to(HERE.parents[1])}: {len(picked)} takes, {n} frames for the TS port to match")


if __name__ == "__main__":
    raise SystemExit(main())
